#!/usr/bin/env python3
"""Retain UIKit geometry as independent C++ regression expectations."""
import argparse,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
path=root/'docs/slider/native/final-geometry/light/geometry.json'
data=json.loads(path.read_text())
lines=['#pragma once','// Generated by Demo/SliderComparison/generate-geometry.py; native UIKit 27.0.',f'// Source SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}',
'struct SliderNativeGeometry { const char* id; NXRect bounds,track,thumb0,thumbHalf,thumb1,minImage,maxImage; float minimum,maximum,value; int style; bool enabled; };',
'inline const SliderNativeGeometry sliderNativeGeometry[] = {']
for c in data['cases']:
 def rect(key):return '{'+','.join(str(x) for x in c[key])+'}'
 lines.append('    {'+json.dumps(c['id'])+','+','.join(rect(k) for k in ['bounds','track','thumbAt0','thumbAtHalf','thumbAt1','minImageRect','maxImageRect'])+','+','.join(str(c[k]).lower() for k in ['minimum','maximum','value','style','enabled'])+'},')
lines+=['};','']
output=root/'UIKit/tests/SliderNativeGeometryData.hpp';text='\n'.join(lines)
if args.check:
 assert output.read_text()==text,'Native slider geometry expectations need regeneration'
 print('Verified',len(data['cases']),'independent UIKit geometry cases')
else:output.write_text(text)
