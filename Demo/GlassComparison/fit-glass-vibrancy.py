"""Fit a bounded color-dependent transfer to public UITabBar palette probes.
Usage: fit-glass-vibrancy.py NATIVE_DIRECTORY SYSTEM_COLORS_JSON OUTPUT [--header PATH]
Green is held out from fitting. No renderer or pixel alignment is fitted.
"""
from pathlib import Path
import json,sys,itertools,hashlib
import numpy as np
from PIL import Image
native,colorsPath,out=map(Path,sys.argv[1:4]);out.mkdir(parents=True,exist_ok=True)
colors=json.loads(colorsPath.read_text());samples=[]
for meta in sorted(native.glob('tabs-*.json')):
 d=json.loads(meta.read_text());a=np.array(Image.open(meta.with_suffix('.png')),float)/255
 for i,t in enumerate(d['tabs']):
  x,y,w,h=t['images'][1];scale=d['scale'];r=slice(round((y+5)*scale),round((y+h-5)*scale));c=slice(round((x+5)*scale),round((x+w-5)*scale))
  observed=np.median(a[r,c,:3],axis=(0,1));bg=np.median(a[r,round((x-6)*scale):round((x-4)*scale),:3],axis=(0,1))
  dark=bool(d['request']['dark']);source=np.array(colors['dark' if dark else 'light'][i][:3])/255
  samples.append(dict(case=meta.stem,dark=dark,index=i,source=source.tolist(),background=bg.tolist(),observed=observed.tolist(),validation=meta.stem.endswith('-green')))
def nnls(x,y):
 best=(float('inf'),np.zeros(3))
 for n in range(4):
  for subset in itertools.combinations(range(3),n):
   coeff=np.zeros(3)
   if subset:
    value=np.linalg.lstsq(x[:,subset],y,rcond=None)[0]
    if min(value)<0:continue
    coeff[list(subset)]=value
   err=np.square(x@coeff-y).sum()
   if err<best[0]:best=(err,coeff)
 return best[1]
profiles={};scores=[]
for dark in [False,True]:
 profiles['dark' if dark else 'light']=[]
 for i in range(12):
  rows=[r for r in samples if r['dark']==dark and r['index']==i and not r['validation']];s=np.array(rows[0]['source']);co=[]
  # Each foreground channel has its own nonnegative background transfer.
  # Reject clipped output samples: they constrain bounds, not the slope.
  for channel in range(3):
   valid=[r for r in rows if .005<r['observed'][channel]<.995]
   if valid:
    x=np.array([np.array(r['background']) if dark else 1-np.array(r['background']) for r in valid])
    y=np.array([(r['observed'][channel]-s[channel]) if dark else (s[channel]-r['observed'][channel]) for r in valid])
    co.append(nnls(x,y).tolist())
   else:co.append([0,0,0])
  profiles['dark' if dark else 'light'].append(dict(source=s.tolist(),matrix=co))
for r in samples:
 p=profiles['dark' if r['dark'] else 'light'][r['index']];d=np.array(r['background']);s=np.array(r['source']);prediction=np.clip(s+(1 if r['dark'] else -1)*np.array(p['matrix'])@(d if r['dark'] else 1-d),0,1);r['predicted']=prediction.tolist();r['MAE255']=float(abs(prediction-r['observed']).mean()*255)
result=dict(method=__doc__,profiles=profiles,samples=samples,meanTrainingMAE255=float(np.mean([r['MAE255'] for r in samples if not r['validation']])),meanValidationMAE255=float(np.mean([r['MAE255'] for r in samples if r['validation']])),sourceSHA256={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in native.glob('tabs-*.json')})
(out/'transfer.json').write_text(json.dumps(result,indent=2)+'\n');print('training/validation',result['meanTrainingMAE255'],result['meanValidationMAE255'])
if '--header' in sys.argv:
 header=Path(sys.argv[sys.argv.index('--header')+1]);rows=[]
 def f3(v):return 'float3('+','.join(f'{x:.8f}' for x in v)+')'
 for theme in ['light','dark']:
  for i,p in enumerate(profiles[theme]):rows.append('  { '+f3(p['source'])+', '+','.join(f3(v) for v in p['matrix'])+' }')
 text="""#pragma once
// Public UIKit 27.0 system-tint transfer; generated by fit-glass-vibrancy.py.
// See docs/liquid-glass-colors/transfer.json. This is a behavioral
// approximation, not Apple's private blend equation.
namespace NXKit::Internal {
inline constexpr const char* glassVibrancySource = R"sksl(
struct VibrancyProfile { float3 color; float3 red; float3 green; float3 blue; };
VibrancyProfile glassVibrancyProfile(int index,float dark) {
"""
 for theme in ['dark','light']:
  text+=('if(dark>.5) {\n' if theme=='dark' else 'else {\n')
  for i,p in enumerate(profiles[theme]):text+='if(index=='+str(i)+')return VibrancyProfile('+f3(p['source'])+','+','.join(f3(v) for v in p['matrix'])+');\n'
  text+='}\n'
 text+="""return VibrancyProfile(float3(0),float3(0),float3(0),float3(0));
}
float3 glassVibrantColor(float3 source, float3 backdrop, float dark) {
  source=clamp(source,0.0,1.0);backdrop=clamp(backdrop,0.0,1.0);
  // Positive bounded interpolation is continuous between measured tints.
  float3 change=float3(0);float total=0.0;
  float3 underlay=dark>.5 ? backdrop : 1.0-backdrop;
  for(int i=0;i<12;++i) {
    VibrancyProfile profile=glassVibrancyProfile(i,dark);
    float3 delta=source-profile.color;float distance=dot(delta,delta);
    float3 value=float3(dot(profile.red,underlay),dot(profile.green,underlay),dot(profile.blue,underlay));
    if(distance<.000001)return clamp(source+(dark>.5?value:-value),0.0,1.0);
    float weight=1.0/(distance*distance);change+=value*weight;total+=weight;
  }
  change/=max(total,.0001);
  return clamp(source+(dark>.5?change:-change),0.0,1.0);
}
)sksl";
}
"""
 header.write_text(text)
