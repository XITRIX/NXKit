#!/usr/bin/env python3
"""Generate shared LensView retirement expectations from captured native inputs."""
import argparse,csv,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
lines=['#pragma once','// Native real-touch UITabBar filter inputs, iOS27.0/24A434; generated by Demo/GlassComparison/generate-tab-shadow.py.',
'struct NativeTabShadowSample { bool dark; double time; float face, refraction, height, shadow, radius, ring; };',
'inline const NativeTabShadowSample nativeTabShadowSamples[] = {']
count=0
for dark in [False,True]:
 path=root/'docs/liquid-glass-lens/tab-shadow/native'/('tab-shadow-dark' if dark else 'tab-shadow-light');raw=(path/'inputs.csv').read_bytes();fit=json.loads((path/'clock-fit.json').read_text())
 lines.append('// inputs.csv SHA256 '+hashlib.sha256(raw).hexdigest())
 for row in csv.DictReader(raw.decode().splitlines()):
  time=float(row['endRelativeSeconds'])-fit['alignmentSeconds'];q=float(row['inputFaceOpacity'])
  if not (0<time<.45 and .001<q<.999):continue
  values=[q]+[float(row[k]) for k in ['inputInnerRefractionAmount','inputInnerRefractionHeight','inputShadowAmount','inputShadowRadius','inputRingShadowOpacity']]
  count+=1
  lines.append('{'+str(dark).lower()+','+format(time,'.12g')+','+','.join(format(v,'.12g')+'f' if '.' in format(v,'.12g') or 'e' in format(v,'.12g') else format(v,'.12g') for v in values)+'},')
lines+=['};',''];text='\n'.join(lines);out=root/'UIKit/tests/NativeTabShadowData.hpp'
if a.check:assert out.read_text()==text,'Regenerate native tab shadow data'
else:out.write_text(text)
print('Verified' if a.check else 'Generated',count,'native tab shadow expectation rows')
