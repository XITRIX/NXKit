#!/usr/bin/env python3
"""Generate expectations from native layer measurements, never from our mapper."""
import argparse, gzip, hashlib, json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--source',type=Path,default=root/'docs/slider/endpoints/native');p.add_argument('--check',action='store_true');a=p.parse_args()
paths=sorted(a.source.rglob('geometry.json.gz'));assert paths,'Missing native endpoint captures'
lines=['#pragma once','// Generated by Demo/SliderComparison/generate-endpoints.py; native UIKit27.0.',
       '// Inputs are retained native model-layer measurements; no endpoint equation is evaluated here.',
       'struct SliderNativeEndpoint { const char* variant; bool dark; float width, minimum, maximum, value, trackX, trackWidth, fillX, fillWidth; };',
       'inline const SliderNativeEndpoint sliderNativeEndpoints[] = {']
count=0
for path in paths:
 raw=gzip.decompress(path.read_bytes());d=json.loads(raw);cfg=d['configuration'];kind=cfg['variant']
 # Custom track images activate UIKit's legacy non-LiquidLens provider.
 if kind=='track-images':continue
 lines.append('// '+str(path.relative_to(a.source))+' SHA256 '+hashlib.sha256(raw).hexdigest())
 for row,frame in zip(d['fresh'],d['rowFrames']):
  fill=row['tree']['children'][0]['children'][0]['children'][1]['model']['frame']
  value=row['minimum']+row['requestedProgress']*(row['maximum']-row['minimum']) if cfg.get('continuousTicks') else row['value']
  nums=[frame[2],row['minimum'],row['maximum'],value,row['track'][0],row['track'][2],fill[0],fill[2]]
  lines.append('    {'+json.dumps(kind)+','+str(cfg['dark']).lower()+','+','.join(format(float(n),'.10g')+'f' if '.' in format(float(n),'.10g') or 'e' in format(float(n),'.10g') else format(float(n),'.10g') for n in nums)+'},');count+=1
lines+=['};',''];text='\n'.join(lines);out=root/'UIKit/tests/SliderNativeEndpointData.hpp'
if a.check:assert out.read_text()==text,'Regenerate native endpoint expectations'
else:out.write_text(text)
print('Verified' if a.check else 'Generated',count,'native endpoint cases')
