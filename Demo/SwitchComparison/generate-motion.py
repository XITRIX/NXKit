#!/usr/bin/env python3
"""Extract immutable UIKit knob bounds/position samples, without refitting them."""
import argparse
import gzip
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
native = root / 'docs/switch/native'

def trace(name):
    with gzip.open(native / name / 'trace.json.gz', 'rt') as source:
        return json.load(source)

def lens(frame):
    return next(layer for layer in frame['layers'] if layer['path'] == 'slider.0.2')

programmatic = trace('programmatic-light')
operation = programmatic['actions'][0]['t']
# The first sampled commit has diagnostic timestamp jitter. All subsequent
# presentation samples share this constant observed phase, with no time warp.
position_phase = 0.063599125
position = [(f['displayTimestamp'] - operation - position_phase,
             (lens(f)['presentationFrame'][0] - 2) / 22)
            for f in programmatic['frames'][2:]
            if 0 < f['displayTimestamp'] - operation - position_phase < .55]

held = trace('on-hold-dark')
release = held['touches'][-1]['dispatchT']
lower_phase = -0.0012307
lowering = [(f['displayTimestamp'] - release - lower_phase,
             lens(f)['presentationBounds'][2], lens(f)['presentationBounds'][3])
            for f in held['frames']
            if .015 < f['displayTimestamp'] - release < .45]

lines = ['// Generated by Demo/SwitchComparison/generate-motion.py. Do not edit.',
         '#pragma once', 'namespace NXKit::Internal {',
         'struct SwitchPositionSample { double time, fraction; };',
         'inline constexpr SwitchPositionSample switchNativeProgrammaticPosition[] = {']
lines += [f'    {{{t:.12g}, {x:.12g}}},' for t, x in position]
lines += ['};', 'struct SwitchBoundsSample { double time, width, height; };',
          'inline constexpr SwitchBoundsSample switchNativeLoweringBounds[] = {']
lines += [f'    {{{t:.12g}, {w:.12g}, {h:.12g}}},' for t, w, h in lowering]
lines += ['};', '} // namespace NXKit::Internal', '']
output = root / 'UIKit/tests/SwitchNativeMotionData.hpp'
expected = '\n'.join(lines)
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not output.exists() or output.read_text() != expected:
        raise SystemExit('Switch native motion data is stale')
else:
    output.write_text(expected)
print(f'Checked {len(position)} position and {len(lowering)} lowering samples')
