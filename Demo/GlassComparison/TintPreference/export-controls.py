#!/usr/bin/env python3
"""Export independently captured flat colors for GlassMaterialTests."""
from pathlib import Path
import json,sys
from PIL import Image
native,output=map(Path,sys.argv[1:3]);lines=['// iOS 27.1 (24A94401), simctl framebuffer controls. Generated by TintPreference/export-controls.py.', '// amount, dark, clear, tinted, width, height, background RGB, native RGB']
for meta in sorted(native.glob('*.json')):
 m=json.loads(meta.read_text());c=m['case']
 if c['id'][0]=='2':continue
 if m.get('capture')!='simctl framebuffer':raise ValueError('Expected composited framebuffer reference')
 im=Image.open(native/(meta.stem+'.png')).convert('RGB');s=m['scale']
 for q in c['probes']:
  x,y,w,h=q['frame'];rgb=im.getpixel((round((x+w/2)*s),round((y+h/2)*s)))
  bg=[(0,0,0),(128,128,128),(255,255,255),(255,0,0),(0,255,0),(0,0,255)][int(c['id'][0])*3+q['column']]
  values=[(f'{m["amount"]:g}f' if m['amount']%1 else f'{m["amount"]:.1f}f'),str(int(c['dark'])),str(int(q['clear'])),str(int(q['tinted'])),str(int(w)),str(int(h))]+list(map(str,bg+rgb))
  lines.append('{'+','.join(values)+'},')
output.write_text('\n'.join(lines)+'\n')
