#!/usr/bin/env python3
"""Use retained native OS-touch presentation samples as independent expectations."""
import argparse,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
lines=['#pragma once','// Generated by Demo/SliderComparison/generate-release-timing.py; UIKit27.0.',
'// Times subtract the previously measured16.5ms release commit interval.',
'struct SliderNativeReleaseSample { double time; float width; };',
'struct SliderNativeReleaseTrace { const char* id; std::vector<SliderNativeReleaseSample> samples; };',
'inline const SliderNativeReleaseTrace sliderNativeReleaseTraces[] = {']
for name in ['velocity-200','velocity-400']:
 directory=root/'docs/slider/native/velocity'/name;raw=(directory/'frames.json').read_bytes();frames=json.loads(raw);touches=(directory/'touches.json').read_bytes()
 up=next(t['t'] for t in json.loads(touches) if t['phase']==3)
 lines+=['// Frames SHA256: '+hashlib.sha256(raw).hexdigest(),'// Touches SHA256: '+hashlib.sha256(touches).hexdigest(),'{"velocity/'+name+'",{']
 for frame in frames:
  time=frame['t']-up-.0165
  if 0<=time<=.46:lines.append('{'+format(time,'.12g')+','+format(frame['presentationBounds'][2],'.12g')+'f},')
 lines.append('}},')
lines+=['};',''];text='\n'.join(lines);out=root/'UIKit/tests/SliderNativeReleaseData.hpp'
if a.check:assert out.read_text()==text,'Regenerate native moving-release expectations'
else:out.write_text(text)
print('Verified' if a.check else 'Generated','native moving-release expectations')
